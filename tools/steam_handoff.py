#!/usr/bin/env python3
"""steam_handoff.py: assemble docs/STEAM.md and render the Steamworks Chrome brief (s1_17, S1 P5).

    python3 tools/steam_handoff.py --write    rebuild docs/STEAM.md from docs/steam/*.md fragments + steam/handoff.json
    python3 tools/steam_handoff.py --check    check.sh block: STEAM.md is current, every referenced repo file exists,
                                              steps numbered contiguously, every placeholder sits in the ledger,
                                              no ledger placeholder while steam-upload is enabled
    python3 tools/steam_handoff.py --kit [OUT]  build/steam_kit/: app_icon_184.jpg, shortcut_icon_512.png,
                                              rich_presence_english.vdf and achievements/ when their data exists
    python3 tools/steam_handoff.py --set-ids APP WIN LINUX   record ids into steam/steam_config.json + handoff ledger

Fragments: each S1 package writes docs/steam/<topic>.md; after a merge run --write once. The brief
section between the steam-handoff markers is generated: never edit it by hand. stdlib (+ Pillow for --kit).
"""
import datetime, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DOC = os.path.join(ROOT, "docs", "STEAM.md")
FRAG = os.path.join(ROOT, "docs", "steam")
HJ = os.path.join(ROOT, "steam", "handoff.json")
CFG = os.path.join(ROOT, "steam", "steam_config.json")
ORDER = ["builds", "p1", "backends", "achievements", "p2", "deck", "p3", "coop", "input", "perf", "p4",
         "upload", "p5", "store", "p6", "ratings"]
BEGIN, END = "<!-- steam-handoff:begin (generated by tools/steam_handoff.py; do not edit) -->", "<!-- steam-handoff:end -->"

HEAD = """# Dreams on Steam

Everything for the Steam release (CONDUCT S1, 2026-11). Assembled by `python3 tools/steam_handoff.py --write`
from the fragments in `docs/steam/` (one per S1 package) plus the generated Chrome brief at the end, which
comes from `steam/handoff.json`. Edit the fragments or the JSON, never this file directly.

The web/phone build is unchanged by all of this: nothing Steam loads on web.

Status words used below: **done** (in the repo and tested), **staged** (written and checked, waiting on
Tom's Steamworks account), **waiting on Tom** (a decision only he makes; never invented).
"""


def load():
    return json.load(open(HJ))


def fragments():
    if not os.path.isdir(FRAG):
        return []
    names = [n for n in os.listdir(FRAG) if n.endswith(".md")]

    def key(n):
        b = n[:-3].lower()
        return (ORDER.index(b) if b in ORDER else len(ORDER), b)
    return sorted(names, key=key)


