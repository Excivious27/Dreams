def calendar(h):
    d0 = h["ledger"].get("fee_paid_D0", "PLACEHOLDER")
    try:
        d = datetime.date.fromisoformat(d0)
    except ValueError:
        return ["D0 = the day the app credit is paid (not yet). Then: D0..D0+7 business days tax check; ~D0+2 Part A done and store submitted; ~D0+7..9 store approved, Coming Soon published; ~D0+10..20 Part B; release no earlier than max(D0+30, coming soon+14, build approved)."]
    f = lambda n: (d + datetime.timedelta(days=n)).isoformat()
    return ["D0 %s fee paid" % d, "~%s store page submitted" % f(2), "~%s store approved, Coming Soon live" % f(9),
            "%s..%s Part B (RC, build review, Deck review)" % (f(10), f(20)), "earliest release %s (D0+30; also coming soon+14 and build approved)" % f(30)]


def render_brief(h):
    out = [BEGIN, "", "## When Tom's Steamworks account is ready (one Chrome session, then timed follow-ups)", "",
           "Run by Claude in Chrome in Tom's own signed-in browser, one step at a time. Tom only signs in, approves Steam Guard on his phone, answers the legal/tax/bank fields, picks the builder inbox, and taps any captcha. Every value below comes from `steam/handoff.json`; uploads come from the kit (`python3 tools/steam_handoff.py --kit`, published by the steam-kit workflow as a draft release so the play site never changes).", ""]
    for part, ss in steps(h):
        title = {"A": "Part A: the one session", "B": "Part B: after the store page is approved", "C": "Part C: release"}[part]
        out += ["### " + title, ""]
        for i, (t, body) in enumerate(ss):
            out.append("- **%s%d. %s.** %s" % (part, i, t, body))
        out.append("")
    out += ["### Calendar", ""] + ["- " + x for x in calendar(h)] + [""]
    out += ["### Kit (file -> Steamworks field)", ""] + ["- `%s`: %s" % kv for kv in h["kit"].items()] + [""]
    out += ["### Values recorded this session", "", "| value | recorded |", "|---|---|"]
    out += ["| %s | %s |" % kv for kv in h["ledger"].items()] + [""]
    out += ["### Waiting on Tom (never invented)", ""]
    w = [k for k, v in _walk(h) if isinstance(v, str) and v.startswith("WAITING ON TOM")]
    out += ["- " + k for k in w] + ["", END, ""]
    return "\n".join(out)


def _walk(o, p=""):
    if isinstance(o, dict):
        for k, v in o.items():
            yield from _walk(v, (p + "." if p else "") + k)
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from _walk(v, "%s[%d]" % (p, i))
    else:
        yield p, o


def build_doc():
    h = load()
    parts = [HEAD, "## Contents", ""]
    fr = fragments()
    parts += ["- docs/steam/%s" % n for n in fr] + ["- When Tom's Steamworks account is ready (generated)", ""]
    for n in fr:
        txt = open(os.path.join(FRAG, n)).read().strip()
        parts += ["<!-- fragment: docs/steam/%s -->" % n, txt, ""]
    parts.append(render_brief(h))
    return "\n".join(parts)


def check():
    errs = []
    h = load()
    if not os.path.isfile(DOC):
        errs.append("docs/STEAM.md missing: run python3 tools/steam_handoff.py --write")
    elif open(DOC).read() != build_doc():
        errs.append("docs/STEAM.md is stale: run python3 tools/steam_handoff.py --write (never edit it by hand)")
    blob = json.dumps(h)
    for ref in set(re.findall(r"((?:docs|steam|tools|data|web|scripts)/[A-Za-z0-9_./-]+\.(?:md|txt|json|in|py|gd|png|yml))", blob)):
        # every referenced file must exist (the S1 store drafts are merged since the integration)
        p = os.path.join(ROOT, ref)
        if not os.path.exists(p):
            errs.append("handoff.json references missing %s" % ref)
    for part, ss in steps(h):
        if not ss:
            errs.append("part %s empty" % part)
    for k, v in _walk(h):
        if isinstance(v, str) and "PLACEHOLDER" in v and not k.startswith("ledger."):
            errs.append("placeholder outside the ledger: %s" % k)
    cfg = json.load(open(CFG))
    if cfg.get("enabled"):
        bad = [k for k, v in h["ledger"].items() if "PLACEHOLDER" in str(v) and k in ("app_id", "depot_windows", "depot_linux", "builder_account")]
        if bad:
            errs.append("steam-upload enabled while the ledger still has placeholders: %s" % bad)
    # s1_17-06: rich presence tokens in code and data stay in step (once P2's files exist)
    rp = os.path.join(ROOT, "data", "rich_presence.json")
    if os.path.isfile(rp):
        d = json.load(open(rp))
        raw = d.get("tokens", d) if isinstance(d, dict) else {}
        # data keys are bare ("Farm"); Steam and the scripts use "#Farm"
        toks = set(k if k.startswith("#") else "#" + k for k in raw.keys())
        used = set()
        for fn in os.listdir(os.path.join(ROOT, "scripts")):
            if fn.endswith(".gd"):
                used |= set(re.findall(r'"(#Status_\w+)"', open(os.path.join(ROOT, "scripts", fn)).read()))
        for t in sorted(used - toks):
            errs.append("rich presence token %s used in scripts but missing from data/rich_presence.json" % t)
        for k in sorted(raw):
            t = k if k.startswith("#") else "#" + k
            if len(str(raw[k])) > 60:
                errs.append("rich presence %s longer than 60 chars" % t)
    for f in ["steam/templates/app_build.vdf.in", ".github/workflows/steam-upload.yml", ".github/workflows/steam-login.yml", "tools/steam/upload.sh"]:
        if not os.path.exists(os.path.join(ROOT, f)):
            errs.append("missing " + f)
    return errs


def kit(out):
    from PIL import Image
    os.makedirs(out, exist_ok=True)
    src = Image.open(os.path.join(ROOT, "web", "icon_512.png")).convert("RGBA")
    src.resize((512, 512), Image.NEAREST).save(os.path.join(out, "shortcut_icon_512.png"))
    bg = Image.new("RGBA", (512, 512), (18, 18, 28, 255))  # boot_splash/bg_color 0.07,0.07,0.11
    bg.alpha_composite(src.resize((512, 512), Image.NEAREST))
    bg.convert("RGB").resize((184, 184), Image.LANCZOS).save(os.path.join(out, "app_icon_184.jpg"), quality=92)
    made = ["shortcut_icon_512.png", "app_icon_184.jpg"]
    rp = os.path.join(ROOT, "data", "rich_presence.json")
    if os.path.isfile(rp):
        d = json.load(open(rp))
        toks = d.get("tokens", d) if isinstance(d, dict) else {}
        lines = ['"lang"', "{", '\t"Language" "english"', '\t"Tokens"', "\t{"]
        for k, v in toks.items():
            if not str(k).startswith("_"):
                lines.append('\t\t"%s" "%s"' % (k if k.startswith("#") else "#" + k, str(v).replace('"', "'")))
        lines += ["\t}", "}"]
        open(os.path.join(out, "rich_presence_english.vdf"), "w").write("\n".join(lines) + "\n")
        made.append("rich_presence_english.vdf")
    made += kit_achievements(out)
    for n in made:
        print("kit: " + os.path.join(out, n))
    return made


def kit_achievements(out):
    """achievements/: definitions.csv (API name, name, description, hidden, stat, icons) + 256x256 colour and
    greyscale locked PNGs, from P2's data/achievements.json. Steamworks' bulk-import header is not public: the
    session exports the empty tab first and maps these columns onto it (s1_17-05)."""
    from PIL import Image, ImageOps
    src = os.path.join(ROOT, "data", "achievements.json")
    if not os.path.isfile(src):
        print("kit: WARN data/achievements.json not in this branch yet (P2): achievements/ skipped")
        return []
    d = json.load(open(src))
    lst = d.get("achievements", d) if isinstance(d, dict) else d
    if isinstance(lst, dict):
        lst = [dict(v, id=k) for k, v in lst.items() if isinstance(v, dict)]
    od = os.path.join(out, "achievements")
    os.makedirs(od, exist_ok=True)
    man = {}
    try:
        man = json.load(open(os.path.join(ROOT, "art", "gen", "manifest.json")))
    except (OSError, ValueError):
        pass
    import csv
    rows, miss = [], []
    for a in lst:
        aid = str(a.get("id", ""))
        api = "ACH_" + re.sub(r"[^A-Z0-9_]", "_", aid.upper())
        icon = None
        for key in (a.get("icon_id"), "ach_" + aid, "achievements/" + aid):
            e = man.get(key) if key else None
            if isinstance(e, dict) and e.get("file"):
                icon = os.path.join(ROOT, "art", "gen", e["file"])
                break
        if icon and os.path.isfile(icon):
            im = Image.open(icon).convert("RGBA").resize((256, 256), Image.NEAREST)
            bg = Image.new("RGBA", im.size, (18, 18, 28, 255))
            bg.alpha_composite(im)
            bg.convert("RGB").save(os.path.join(od, api + ".png"))
            ImageOps.grayscale(bg.convert("RGB")).save(os.path.join(od, api + "_locked.png"))
        else:
            miss.append(aid)
        rows.append([api, a.get("name", ""), a.get("description", a.get("desc", "")), "1" if a.get("hidden") else "0",
                     a.get("stat", ""), api + ".png", api + "_locked.png"])
    with open(os.path.join(od, "definitions.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["api_name", "display_name", "description", "hidden", "stat", "icon", "icon_locked"])
        w.writerows(rows)
    if miss:
        print("kit: WARN %d achievements without a sliced icon: %s" % (len(miss), ", ".join(miss[:8])))
    return ["achievements/definitions.csv (%d)" % len(rows)]


def check_kit(out):
    from PIL import Image
    errs = []
    a = Image.open(os.path.join(out, "app_icon_184.jpg"))
    if a.size != (184, 184) or a.mode != "RGB":
        errs.append("app_icon_184.jpg must be 184x184 RGB (no alpha)")
    s = Image.open(os.path.join(out, "shortcut_icon_512.png"))
    if s.size != (512, 512):
        errs.append("shortcut_icon_512.png must be 512x512")
    return errs


def set_ids(app, win, lin):
    cfg = json.load(open(CFG))
    cfg["app_id"], cfg["depots"] = int(app), {"windows": int(win), "linux": int(lin)}
    json.dump(cfg, open(CFG, "w"), indent=1)
    h = load()
    h["ledger"].update(app_id=str(app), depot_windows=str(win), depot_linux=str(lin))
    json.dump(h, open(HJ, "w"), indent=1, ensure_ascii=False)
    open(DOC, "w").write(build_doc())


def main():
    a = sys.argv[1:]
    if "--write" in a:
        open(DOC, "w").write(build_doc())
        print("steam_handoff: wrote docs/STEAM.md (%d fragments)" % len(fragments()))
        return 0
    if "--kit" in a:
        i = a.index("--kit")
        out = a[i + 1] if len(a) > i + 1 else os.path.join(ROOT, "build", "steam_kit")
        kit(out)
        e = check_kit(out)
        for x in e:
            print("steam_handoff: FAIL " + x)
        return 1 if e else 0
    if "--set-ids" in a:
        i = a.index("--set-ids")
        set_ids(*a[i + 1:i + 4])
        return 0
    e = check()
    for x in e:
        print("steam_handoff: FAIL " + x)
    if not e:
        print("steam_handoff: OK (%d fragments, brief current)" % len(fragments()))
    return 1 if e else 0


if __name__ == "__main__":
    sys.exit(main())
