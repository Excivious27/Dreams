#!/usr/bin/env python3
"""Player-facing counts for the Steam store copy (CONDUCT S1, P6).

Writes docs/steam-store/facts.json from data/*.json so store drafts never carry
hand-typed numbers. Each count has an exact value and a conservative marketing
floor ("130+"). Drafts use tokens like {crops_floor}; tools/store_text_check.py
renders them, fails when facts.json is stale, and fails when a literal number
in a draft is higher than its fact. Called from tools/regen_data.sh.
stdlib only.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "docs", "steam-store", "facts.json")
TITLE = "Dreams (working title)"  # the one place the store title lives; rename = one line


def load(name):
    with open(os.path.join(DATA, name)) as f:
        return json.load(f)


def floor(n):
    """Round DOWN to a marketing floor: 134 -> '130+', 1038 -> '1,000+', 27 -> '25+', 9 -> '9'."""
    if n >= 1000:
        step = 100 if n < 2000 else 500
    elif n >= 100:
        step = 10
    elif n >= 20:
        step = 5
    else:
        return str(n)
    v = n // step * step
    return ("{:,}".format(v)) + ("+" if v < n or n >= 20 else "")


def counts():
    crops = load("crops.json")
    crops_n = sum(1 for k, v in crops.items() if isinstance(v, dict) and not (v.get("test") or v.get("unused")))
    npcs = load("npcs.json")
    villagers = sum(1 for v in npcs.values() if isinstance(v, dict) and v.get("name"))
    q = load("quests.json")
    regions = load("regions.json")
    mega = load("mega_regions.json").get("list", [])
    enemies = load("enemies.json").get("enemies", {})
    romance = load("romance.json").get("candidates", {})
    decor = load("decor.json").get("items", {})
    ward = load("wardrobe.json").get("items", {})
    ranch = load("ranch.json")
    planned = ranch.get("planned") or []
    species = [k for k in ranch.get("species", {}) if k not in planned]
    battles = [k for k in load("battles.json") if k.startswith("bf_")]
    cabinets = load("rec.json").get("cabinets", [])
    songs = len(glob.glob(os.path.join(ROOT, "audio", "music", "*.ogg")))
    return {
        "crops": crops_n, "villagers": villagers,
        "main_quests": len(q.get("main", [])), "side_quests": len(q.get("side", [])),
        "regions": len(regions), "mega": len(mega), "enemies": len(enemies),
        "romance": len(romance), "decor": len(decor), "outfits": len(ward),
        "ranch_species": len(species), "battlefields": len(battles),
        "arcade": len(cabinets), "songs": songs,
    }


def build():
    c = counts()
    facts = {"_note": "Generated by tools/store_facts.py from data/*.json; never edit by hand.",
             "title": TITLE}
    for k, v in sorted(c.items()):
        facts[k] = v
        facts[k + "_floor"] = floor(v)
    return facts


def main():
    facts = build()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    text = json.dumps(facts, indent=1, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        if old != text:
            print("store_facts: docs/steam-store/facts.json is stale: run python3 tools/store_facts.py")
            return 1
        print("store_facts: ok")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("store_facts: wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
