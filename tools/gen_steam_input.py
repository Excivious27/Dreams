#!/usr/bin/env python3
"""S1 P4: write steam/input/game_actions_480.vdf (Steam Input "In Game Actions")
from scripts/input_setup.gd, so the Steam Input action names are InputSetup's own
action ids (a later SteamService input bridge can call Input.action_press(id)).

Rename to game_actions_<appid>.vdf when Tom's App ID exists (docs/steam/coop.md).
Keyboard-only quick slots (slot_N) are left out. 'journal' has no Xbox-pad button
(no free face button) and is offered for the Deck's L4 back grip.
Usage: python3 tools/gen_steam_input.py [--check]   (--check: exit 1 if the file is stale)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "scripts", "input_setup.gd")
OUT = os.path.join(ROOT, "steam", "input", "game_actions_480.vdf")

MOVE = ["up", "down", "left", "right"]
TRIGGERS = {"dodge", "ability"}            # LT / RT (axis codes in PAD_DEFAULTS)
EXTRA_INGAME = ["journal"]                 # no Xbox button; Deck L4 grip in the default layout
MENU_SET = ["a", "b", "menu", "cycle_back", "cycle_tool"]
WORDS = {
    "a": "Use / Confirm", "b": "Back / Run", "tool": "Use Tool", "action": "Check / Talk",
    "menu": "Menu", "map": "Map", "journal": "Quests", "cycle_back": "Toolbar Back",
    "cycle_tool": "Shift Toolbar", "dodge": "Dodge", "ability": "Partner Ability",
    "pup": "Pup Command", "rally": "Battle Rally",
}


def pad_actions(text: str) -> list:
    m = re.search(r"const PAD_DEFAULTS := \{(.*?)\n\}", text, re.S)
    if not m:
        raise SystemExit("gen_steam_input: PAD_DEFAULTS not found in input_setup.gd")
    return re.findall(r'^\s*"([a-z_0-9]+)"\s*:', m.group(1), re.M)


def token(a: str) -> str:
    return "Action_" + "".join(p.capitalize() for p in a.split("_"))


def build() -> str:
    acts = pad_actions(open(SRC, encoding="utf-8").read())
    unknown = [a for a in acts if a not in MOVE and a not in WORDS]
    if unknown:
        raise SystemExit("gen_steam_input: add words for %s" % unknown)
    buttons = [a for a in acts if a not in MOVE and a not in TRIGGERS] + [a for a in EXTRA_INGAME if a not in acts]
    trig = [a for a in acts if a in TRIGGERS]
    loc = {"Set_InGame": "Playing", "Set_Menu": "Menus", "Action_Move": "Move", "Action_Nav": "Move cursor"}
    t = "\t"
    out = ['// Generated by tools/gen_steam_input.py from scripts/input_setup.gd. Do not edit by hand.',
           '"In Game Actions"', "{", t + '"actions"', t + "{",
           t * 2 + '"InGame"', t * 2 + "{", t * 3 + '"title"' + t + '"#Set_InGame"',
           t * 3 + '"StickPadGyro"', t * 3 + "{", t * 4 + '"Move"', t * 4 + "{",
           t * 5 + '"title"' + t + '"#Action_Move"', t * 5 + '"input_mode"' + t + '"joystick_move"',
           t * 4 + "}", t * 3 + "}", t * 3 + '"AnalogTrigger"', t * 3 + "{"]
    for a in trig:
        out.append(t * 4 + '"%s"%s"#%s"' % (a, t, token(a)))
        loc[token(a)] = WORDS[a]
    out += [t * 3 + "}", t * 3 + '"Button"', t * 3 + "{"]
    for a in buttons:
        out.append(t * 4 + '"%s"%s"#%s"' % (a, t, token(a)))
        loc[token(a)] = WORDS[a]
    out += [t * 3 + "}", t * 2 + "}",
            t * 2 + '"Menu"', t * 2 + "{", t * 3 + '"title"' + t + '"#Set_Menu"',
            t * 3 + '"StickPadGyro"', t * 3 + "{", t * 4 + '"Nav"', t * 4 + "{",
            t * 5 + '"title"' + t + '"#Action_Nav"', t * 5 + '"input_mode"' + t + '"joystick_move"',
            t * 4 + "}", t * 3 + "}", t * 3 + '"Button"', t * 3 + "{"]
    for a in MENU_SET:
        out.append(t * 4 + '"%s"%s"#%s"' % (a, t, token(a)))
        loc[token(a)] = WORDS[a]
    out += [t * 3 + "}", t * 2 + "}", t + "}", t + '"localization"', t + "{",
            t * 2 + '"english"', t * 2 + "{"]
    out.append(t * 3 + '"Title"' + t + '"Dreams (working title)"')
    out.append(t * 3 + '"Description"' + t + '"Default controls for Dreams: Xbox-style layout, Stardew-style buttons."')
    for k in sorted(loc):
        out.append(t * 3 + '"%s"%s"%s"' % (k, t, loc[k]))
    out += [t * 2 + "}", t + "}", "}"]
    return "\n".join(out) + "\n"


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("gen_steam_input: steam/input/game_actions_480.vdf is stale; run python3 tools/gen_steam_input.py")
            sys.exit(1)
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
