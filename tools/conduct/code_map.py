#!/usr/bin/env python3
"""code_map.py <out.md> : the shared code map for a CONDUCT (Tom 22:49, usage optimisation).

Big shared files: key functions with line numbers and a one-line purpose (the ## doc
comment above the func, else the first comment inside it); autoloads; data files and
their generators; test entry points. Agents start here, grep, and read line ranges:
never a whole big file. Kept under ~400 lines.
"""
import os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
BIG = ["game_map.gd", "game_state.gd", "mine.gd", "farm.gd", "player.gd", "hud.gd", "region.gd",
       "game_menu.gd", "music.gd", "danger_music.gd", "ambience.gd", "story.gd", "dialogue.gd",
       "world_gen.gd", "town.gd", "npc.gd", "enemy.gd", "battle.gd", "campaign.gd"]
PER_FILE = {"game_map.gd": 50, "game_state.gd": 40}
DEFAULT_N = 14


def funcs(path, cap):
    lines = open(path, encoding="utf-8", errors="replace").read().split("\n")
    out = []
    for i, l in enumerate(lines):
        m = re.match(r"(static )?func (\w+)\(([^)]*)\)", l)
        if not m:
            continue
        name = m.group(2)
        doc = ""
        j = i - 1
        while j >= 0 and lines[j].startswith("##"):
            doc = lines[j].lstrip("# ").strip() + " " + doc
            j -= 1
        if not doc:
            for k in range(i + 1, min(i + 4, len(lines))):
                c = lines[k].strip()
                if c.startswith("#"):
                    doc = c.lstrip("# ").strip()
                    break
        out.append((i + 1, name, doc.strip()[:90], name.startswith("_") and not doc))
    # keep public + documented first, private undocumented last
    keep = [f for f in out if not f[3]][:cap]
    if len(keep) < cap:
        keep += [f for f in out if f[3]][: cap - len(keep)]
    keep.sort()
    return len(lines), len(out), keep


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "/tmp/code_map.md"
    L = ["# Dreams shared code map (generated by tools/conduct/code_map.py)", "",
         "Rule: start here, `grep -n` for what you need, then read line ranges (Read offset/limit). Never read a whole big file.", ""]
    # autoloads
    pg = open(os.path.join(ROOT, "project.godot"), encoding="utf-8").read()
    al = re.findall(r'^(\w+)="\*?res://([^"]+)"', pg.split("[autoload]")[1].split("\n[")[0], re.M) if "[autoload]" in pg else []
    L.append("## Autoloads")
    L.append(", ".join("%s (%s)" % (a, p) for a, p in al))
    L.append("")
    L.append("## Big shared files: key functions (line: name - purpose)")
    for f in BIG:
        p = os.path.join(ROOT, "scripts", f)
        if not os.path.exists(p):
            continue
        n, nf, keep = funcs(p, PER_FILE.get(f, DEFAULT_N))
        L.append("### scripts/%s (%d lines, %d funcs; showing %d)" % (f, n, nf, len(keep)))
        for ln, name, doc, _ in keep:
            L.append("- %d: %s%s" % (ln, name, (" - " + doc) if doc else ""))
        L.append("")
    # data and generators
    L.append("## Data files and their generators (edit the generator, not the JSON)")
    gens = {}
    for g in sorted(os.listdir(os.path.join(ROOT, "tools"))):
        if g.startswith("gen_") and g.endswith(".py"):
            src = open(os.path.join(ROOT, "tools", g), encoding="utf-8", errors="replace").read()
            for d in sorted(set(re.findall(r"data/(\w+\.json)", src))):
                gens.setdefault(d, []).append(g)
    by_gen = {}
    for d, gl in gens.items():
        by_gen.setdefault(", ".join("tools/" + g for g in gl), []).append(d)
    for g, ds in sorted(by_gen.items()):
        L.append("- %s -> %s" % (g, ", ".join("data/" + d for d in sorted(ds))))
    hand = sorted(d for d in os.listdir(os.path.join(ROOT, "data")) if d.endswith(".json") and d not in gens)
    L.append("- hand-edited: " + ", ".join(hand))
    L.append("")
    # tests
    L.append("## Test entry points")
    L.append("- Full suite: tools/check.sh (CI only: tools/conduct/ci_run.sh). One step: `CHECK_SHARD=i/N` or run the test directly.")
    ck = open(os.path.join(ROOT, "tools", "check.sh"), encoding="utf-8").read()
    tests = sorted(set(re.findall(r"res://tools/(\w+\.gd)", ck)) | set(re.findall(r"python3 tools/(\w+\.py)", ck)))
    L.append("- In check.sh: " + ", ".join(tests))
    L.append("- Run one: `flock /tmp/godot.lock godot --headless [--fixed-fps 60] --path . -s res://tools/<test>.gd`")
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out, len(L), "lines")


if __name__ == "__main__":
    main()
